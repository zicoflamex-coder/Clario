List<Map<String, dynamic>> loadLayout() {
  final s = prefs.getString('wl2');
  if (s == null) return defaultLayout();
  try {
    return (jsonDecode(s) as List)
        .map((e) => Map<String, dynamic>.from(e as Map))
        .where((e) => widgetDefs.any((d) => d.$1 == e['id']))
        .toList();
  } catch (_) {
    return defaultLayout();
  }
}

void saveLayout(List<Map<String, dynamic>> l) {
  prefs.setString('wl2', jsonEncode(l));
  store.poke();
}

void resetLayout() {
  prefs.remove('wl2');
  store.poke();
}

