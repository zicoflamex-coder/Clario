// نزدیک‌ترین روزهای جهانی از امروز (امروز = left صفر)
List<Map<String, dynamic>> upcomingWorldDays(int count) {
  final n = dayOnly(DateTime.now());
  final out = <Map<String, dynamic>>[];
  for (final d in worldDays) {
    var dt = DateTime(n.year, d.$1, d.$2);
    if (dt.isBefore(n)) dt = DateTime(n.year + 1, d.$1, d.$2);
    out.add({'name': d.$3, 'left': dt.difference(n).inDays, 'date': dt});
  }
  out.sort((a, b) => (a['left'] as int).compareTo(b['left'] as int));
  return out.take(count).toList();
}
